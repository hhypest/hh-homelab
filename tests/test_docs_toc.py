"""
Оглавление страниц собирается скриптом из заголовков.

Строитель берёт `h2.textContent`, то есть весь текст внутри заголовка —
включая вложенные элементы. Пока в h2 ничего не вкладывали, это работало.
Стоило поставить туда метку «эта конфигурация», и в боковом оглавлении
появилось «Wi-Fi или кабельэта конфигурация»: пробела между заголовком
и меткой в разметке нет, textContent склеивает их вплотную.

Замечание Codex к PR 40. Ошибка из тех, что не видит ни один валидатор:
HTML корректен, ссылки целы, ломается только то, что рисует браузер.

Тест держит сам инвариант, а не конкретную страницу: положили метку
внутрь h2 — извольте вырезать её при сборке оглавления.
"""

from __future__ import annotations

import pathlib
import re

from conftest import ROOT

DOCS = sorted((ROOT / "docs").glob("*.html"))

# <h2 …> … class="tag" … </h2> — метка внутри заголовка раздела.
H2_WITH_TAG = re.compile(r'<h2[^>]*>(?:(?!</h2>).)*?class="tag(?:(?!</h2>).)*?</h2>', re.S)
# Голое чтение всего текста заголовка в строителе оглавления.
BARE_TEXT = re.compile(r"h2\.textContent(?!\s*\.replace)")


def страницы_с_меткой_в_заголовке() -> list[pathlib.Path]:
    return [p for p in DOCS if H2_WITH_TAG.search(p.read_text(encoding="utf-8"))]


def test_метка_в_заголовке_вообще_встречается():
    """
    Защита от пустой проверки.

    Если метки уберут из всех h2, тест ниже начнёт проходить просто потому,
    что проверять стало нечего. Пусть об этом скажут прямо, а не тишиной.
    """
    assert страницы_с_меткой_в_заголовке(), (
        "ни на одной странице нет метки внутри <h2> — проверка ниже стала пустой"
    )


def test_оглавление_не_подхватывает_метку_из_заголовка():
    for path in страницы_с_меткой_в_заголовке():
        text = path.read_text(encoding="utf-8")
        assert not BARE_TEXT.search(text), (
            f"{path.relative_to(ROOT)}: в <h2> есть метка, но оглавление строится "
            f"из h2.textContent — метка приклеится к заголовку без пробела"
        )
