"""
Сверка версий образов с реестром: разбор тегов и правило «что новее».

Теги здесь не semver, и вся ценность скрипта — в том, как он решает,
какой тег новее. Ошибиться можно в обе стороны, и обе дорого:
промолчать про вышедшее обновление или предложить поднять версию
на ночную сборку.

Сеть тесты не трогают: ответ реестра подставляется списком. Проверяется
именно правило, а не доступность ghcr.io.
"""

from __future__ import annotations

import pytest
from conftest import ROOT, load

ci = load(ROOT / "scripts" / "check_image_updates.py")


# --- форма, скелет, числа -----------------------------------------------

@pytest.mark.parametrize(
    ("тег", "форма"),
    [
        ("5.2.3_v2.0.14-ls474", "N.N.N_vN.N.N-lsN"),
        ("10.11.11ubu2604-ls47", "N.N.NubuN-lsN"),
        ("2026.9.0", "N.N.N"),
        ("v3.5.0", "vN.N.N"),
    ],
)
def test_форма_заменяет_цепочки_цифр(тег: str, форма: str):
    assert ci.форма(тег) == форма


def test_скелет_не_различает_число_частей_версии():
    """
    Ровно тот случай, ради которого скелет и заведён.

    Jellyfin выкинул ведущую «10.» из схемы версий: 10.12.x стало 12.x.
    Форма у тегов разная, линейка одна — и это должно быть видно.
    """
    assert ci.скелет("10.11.11ubu2604-ls47") == ci.скелет("12.1ubu2604-ls50")


@pytest.mark.parametrize(
    ("тег", "скелет"),
    [("sha-8253831", "sha-"), ("3.4-pr-186", ".-pr-"), ("v3.4.1", "v.")],
)
def test_скелет_отличает_чужое_по_природе(тег: str, скелет: str):
    """Числа в этих тегах большие, но версией не являются вовсе."""
    assert ci.скелет(тег) == скелет
    assert ci.скелет(тег) != ci.скелет("2.35.0")


def test_числа_идут_по_порядку():
    assert ci.числа("5.2.3_v2.0.14-ls474") == (5, 2, 3, 2, 0, 14, 474)


# --- что считается выпуском ---------------------------------------------

@pytest.mark.parametrize(
    "тег",
    ["nightly-2.6.5.5620-ls16", "develop-6.4.4.10685-ls267", "2026.9.0b2",
     "sha256-e091b52846a5", "sha-8253831", "1.2.3-rc1", "latest"],
)
def test_не_выпуски_отсеиваются(тег: str):
    assert not ci.релиз(тег)


@pytest.mark.parametrize(
    "тег",
    ["12.1ubu2604-ls50", "2026.9.2", "v3.5.2", "5.2.3_v2.0.14-ls476"],
)
def test_выпуски_проходят(тег: str):
    assert ci.релиз(тег)


# --- разбор ссылки ------------------------------------------------------

def test_разбор_ссылки():
    assert ci.разобрать("lscr.io/linuxserver/jellyfin:10.11.11ubu2604-ls47") == (
        "lscr.io", "linuxserver/jellyfin", "10.11.11ubu2604-ls47"
    )


def test_образ_без_тега_это_ошибка():
    with pytest.raises(ValueError, match="нет тега"):
        ci.разобрать("lscr.io/linuxserver/jellyfin")


def test_ссылка_без_реестра_это_ошибка():
    """Короткая форма ушла бы в Docker Hub — угадывать реестр скрипт не берётся."""
    with pytest.raises(ValueError, match="не указан реестр"):
        ci.разобрать("nginx:1.27")


# --- правило «что новее» ------------------------------------------------

def test_находит_новее_той_же_формы():
    новее, иные = ci.сравнить(
        "5.2.3_v2.0.14-ls474",
        ["5.2.3_v2.0.14-ls473", "5.2.3_v2.0.14-ls475", "5.2.3_v2.0.14-ls476"],
    )
    assert новее == ["5.2.3_v2.0.14-ls475", "5.2.3_v2.0.14-ls476"]
    assert иные == []


def test_ночные_сборки_не_предлагаются():
    """
    У них другая форма, поэтому в сравнение они не попадают вовсе —
    отдельного фильтра для этого не нужно.
    """
    новее, иные = ci.сравнить(
        "2.5.2.5491-ls158",
        ["nightly-2.6.5.5620-ls16", "develop-2.6.4.5611-ls274", "libtorrentv1-5.2.3_v1.2.20-ls132"],
    )
    assert новее == []
    assert иные == []


def test_смена_схемы_нумерации_не_ранжируется_а_показывается():
    новее, иные = ci.сравнить(
        "10.11.11ubu2604-ls47",
        ["10.10.7ubu2404-ls30", "12.0ubu2604-ls48", "12.1ubu2604-ls50",
         "nightly-2026091410ubu2604-ls102"],
    )
    assert новее == [], "переномерованную линейку машина ранжировать не должна"
    assert иные == ["12.0ubu2604-ls48", "12.1ubu2604-ls50"]


def test_старое_из_другой_схемы_не_всплывает():
    """10.10.7 старше закреплённого, и показывать его незачем."""
    _, иные = ci.сравнить("10.11.11ubu2604-ls47", ["10.10.7ubu2404-ls30"])
    assert иные == []


@pytest.mark.parametrize(
    ("закреплён", "доступные"),
    [
        ("v3.4.1", ["sha-7920970", "sha-8563362", "develop"]),
        ("v0.5.0", ["3.2-pr-186", "3.4-pr-185", "3.4-pr-186"]),
        ("2.35.0", ["sha-8253831", "sha-9913482"]),
    ],
)
def test_теги_по_коммиту_и_сборки_pr_не_шумят(закреплён: str, доступные: list[str]):
    """
    Числа в них больше закреплённых, но это не версии. До уточнения
    правила скелетом все три образа попадали в раздел «смотреть».
    """
    новее, иные = ci.сравнить(закреплён, доступные)
    assert новее == []
    assert иные == []


def test_свежий_образ_молчит():
    новее, иные = ci.сравнить("v3.5.2", ["v3.5.0", "v3.5.1", "v3.5.2"])
    assert новее == []
    assert иные == []


# --- разбор compose -----------------------------------------------------

def test_находятся_все_образы_обоих_стеков():
    найдено = {}
    for файл in ci.COMPOSE:
        найдено.update(ci.images(файл))
    assert len(найдено) == 9, f"ожидалось девять образов, найдено {len(найдено)}: {найдено}"
    assert any("DOCKER_MODS" in имя for имя in найдено), (
        "образ из DOCKER_MODS потерялся — ровно его Dependabot и не видит"
    )
    for ссылка in найдено.values():
        ci.разобрать(ссылка)  # каждая ссылка разбирается без исключений
